// Regenerates tests/tools/api-16001.txt from a Ketho/BlizzardInterfaceResources checkout (branch `forever`).
// Usage: node tests/tools/gen-api-list.js <dir with GlobalAPI.lua and FrameXML.lua> [commit]
// Only the quoted names are extracted (one per line, sorted, unique); the dump files are read as data, never executed.
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
const commit = process.argv[3] || 'c5a49d3945';
if (!dir) { console.error('usage: node tests/tools/gen-api-list.js <dumpdir> [commit]'); process.exit(2); }
const names = new Set();
for (const f of ['GlobalAPI.lua', 'FrameXML.lua']) {
  const src = fs.readFileSync(path.join(dir, f), 'utf8');
  for (const m of src.matchAll(/^\s*"([A-Za-z_][A-Za-z0-9_.:]*)",?\s*$/gm)) names.add(m[1]);
}
const header = [
  '# WoW API names for Interface 16001 (WoW Forever 1.60.1, build 70338): global functions, C_* namespaced',
  '# functions, Lua builtins exposed by the client and FrameXML global functions.',
  `# Source: https://github.com/Ketho/BlizzardInterfaceResources branch \`forever\`, commit ${commit} "1.60.1 (70338)",`,
  '# files Resources/GlobalAPI.lua + Resources/FrameXML.lua. Upstream data is Blizzard-derived interface',
  '# metadata redistributed by Ketho/BlizzardInterfaceResources; see that repo for its license/terms.',
  '# Generated by tests/tools/gen-api-list.js; do not edit by hand.',
];
const out = path.join(__dirname, 'api-16001.txt');
fs.writeFileSync(out, header.join('\n') + '\n' + [...names].sort().join('\n') + '\n');
console.log(`wrote ${names.size} names to ${path.relative(process.cwd(), out)}`);
