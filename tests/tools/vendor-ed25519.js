// Builds Core/Ed25519.lua from ccryptolib (MIT, migeyel/ccryptolib) for Lua 5.1 / WoW and Fengari (Lua 5.3).
// Usage: node tests/tools/vendor-ed25519.js <ccryptolib checkout> <packing.gen.lua> > Core/Ed25519.lua
// packing.gen.lua = output of `lua5.1 tests/tools/ed25519-genpack.lua <ccryptolib>/ccryptolib/internal/packing.lua`
// (ccryptolib compiles its packers with load(); we pre-generate them so the addon never calls load/loadstring).
const fs = require('fs'), path = require('path');
const [dir, packGen] = process.argv.slice(2);
const rd = (f) => fs.readFileSync(path.join(dir, 'ccryptolib', f), 'utf8');
const commit = fs.existsSync(path.join(dir, '.git')) ? require('child_process').execSync('git -C ' + dir + ' rev-parse HEAD').toString().trim() : '?';
const mods = { util: 'internal/util.lua', mp: 'internal/mp.lua', fq: 'internal/fq.lua', fp: 'internal/fp.lua', sha512: 'internal/sha512.lua', edwards25519: 'internal/edwards25519.lua' };
function patch(name, s) {
  s = s.replace(/local expect = require "cc\.expect"\.expect/g, 'local expect = function() end');
  s = s.replace(/local hw = require "ccryptolib\.internal\.hw"/g, 'local hw = HW');
  s = s.replace(/require "ccryptolib\.internal\.(\w+)"/g, (_, m) => 'M.' + m);
  s = s.replace(/\\x80/g, '\\128');
  s = s.replace(/\bbit32\./g, 'B32.');
  if (name === 'util') s = 'local unpack = unpack or table.unpack\n' + s;
  if (/\\x|\bload\(|\bbit32\b|cc\.expect|require/.test(s)) throw new Error('unpatched construct in ' + name);
  return s;
}
