// Builds Core/Ed25519.lua from ccryptolib (MIT, migeyel/ccryptolib) for Lua 5.1 / WoW and Fengari (Lua 5.3).
// Usage: node tests/tools/vendor-ed25519.js <ccryptolib checkout> <packing.gen.lua> > Core/Ed25519.lua
// packing.gen.lua = output of `lua5.1 tests/tools/ed25519-genpack.lua <ccryptolib>/ccryptolib/internal/packing.lua`
// (ccryptolib compiles its packers with load(); we pre-generate them so the addon never calls load/loadstring).
const fs = require('fs'), path = require('path');
const [dir, packGen] = process.argv.slice(2);
const rd = (f) => fs.readFileSync(path.join(dir, 'ccryptolib', f), 'utf8');
const commit = fs.existsSync(path.join(dir, '.git')) ? require('child_process').execSync('git -C ' + dir + ' rev-parse HEAD').toString().trim() : '?';
const mods = { util: 'internal/util.lua', mp: 'internal/mp.lua', fq: 'internal/fq.lua', fp: 'internal/fp.lua', sha512: 'internal/sha512.lua', edwards25519: 'internal/edwards25519.lua' };
function patch(name, s) {
  s = s.replace(/local expect = require "cc\.expect"\.expect/g, 'local expect = function() end');
  s = s.replace(/local hw = require "ccryptolib\.internal\.hw"/g, 'local hw = HW');
  s = s.replace(/require "ccryptolib\.internal\.(\w+)"/g, (_, m) => 'M.' + m);
  s = s.replace(/\\x80/g, '\\128');
  s = s.replace(/\bbit32\./g, 'B32.');
  if (name === 'util') s = 'local unpack = unpack or table.unpack\n' + s;
  if (/\\x|\bload\(|\bbit32\b|cc\.expect|require/.test(s)) throw new Error('unpatched construct in ' + name);
  return s;
}
let out = [];
out.push(`-- Guild Squads (MIT) - Core/Ed25519.lua
-- GENERATED by tests/tools/vendor-ed25519.js - do not edit by hand.
-- Ed25519 (RFC 8032) on top of ccryptolib by Miguel Oliveira (migeyel), commit ${commit}.
-- ccryptolib: MIT License, Copyright (c) 2023 Miguel Oliveira. Full notice in docs/licenses/ccryptolib.txt.
-- Changes from upstream: modules inlined; bit32 shim over WoW's bit; packers pre-generated (no load());
-- ComputerCraft hw/expect/random removed; sign() is the deterministic RFC 8032 one (no RNG in WoW);
-- verify() is strict (rejects S >= L, non-canonical or small-order A and small-order R).
-- Pure Lua 5.1/5.3, no WoW API.
local _, ns = ...
ns = ns or {}
local B32
do
  local floor = math.floor
  local bit = rawget(_G, "bit")
  local T32 = 4294967296
  local band, bor, bxor
  if bit then
    band = function(a, b) return bit.band(a, b) % T32 end
    bor = function(a, b) return bit.bor(a, b) % T32 end
    bxor = function(a, b) return bit.bxor(a, b) % T32 end
  else
    -- no bit library (Fengari tests): byte-wise tables; slow but exact
    local AND, OR, XOR = {}, {}, {}
    for x = 0, 255 do for y = 0, 255 do
      local a, o, e, p, xx, yy = 0, 0, 0, 1, x, y
      for _ = 1, 8 do
        local bx, by = xx % 2, yy % 2
        if bx == 1 and by == 1 then a = a + p end
        if bx == 1 or by == 1 then o = o + p end
        if bx ~= by then e = e + p end
        xx, yy, p = (xx - bx) / 2, (yy - by) / 2, p * 2
      end
      local k = x * 256 + y
      AND[k], OR[k], XOR[k] = a, o, e
    end end
    local function op(t)
      return function(a, b)
        local r, p = 0, 1
        for _ = 1, 4 do
          local x, y = a % 256, b % 256
          r = r + t[x * 256 + y] * p
          a, b, p = (a - x) / 256, (b - y) / 256, p * 256
        end
        return r
      end
    end
    band, bor, bxor = op(AND), op(OR), op(XOR)
  end
  B32 = {
    band = band, bor = bor, bxor = bxor,
    bnot = function(a) return T32 - 1 - a % T32 end,
    lshift = function(a, n) return (a % 2 ^ (32 - n)) * 2 ^ n end,
    rshift = function(a, n) return floor((a % T32) / 2 ^ n) end,
    extract = function(a, f) return floor(a / 2 ^ f) % 2 end,
  }
end
local F = function() return false end
local HW = { sha512 = F, ed25519PublicKey = F, ed25519Sign = F, ed25519Verify = F }
local M = {}
M.packing = (function()
${fs.readFileSync(packGen, 'utf8')}end)()
`);
for (const [name, f] of Object.entries(mods)) out.push(`M.${name} = (function()\n${patch(name, rd(f))}\nend)()\n`);
out.push(fs.readFileSync(path.join(__dirname, 'ed25519-api.lua'), 'utf8'));
process.stdout.write(out.join(''));
