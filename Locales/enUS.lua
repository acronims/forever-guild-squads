-- readable text for an error code; never shows a raw ERR_ key
function ns.ErrText(why)
  if why == "notInGuild" and ns.NotInGuildText then   -- roster read and I am missing -> say so
    local honest = ns.NotInGuildText()
    if honest then return honest end
  end
  local t = rawget(ns.L, "ERR_" .. tostring(why))
  if t then return t end
  return (rawget(ns.L, "ERR_unknown") or "unexpected error (%s)"):format(tostring(why))
end
